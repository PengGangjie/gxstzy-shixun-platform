// 公文正文不使用加粗（仿宋伪粗同样有描边风险），强调靠句式
function bodyRich(segments, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 640 },
    spacing: { line: 560, lineRule: "exact", after: 0 },
    children: segments.map(s => new TextRun({ text: s.t, bold: false, size: 32, color: "000000",
      font: { eastAsia: "FangSong", ascii: "Times New Roman" } })),
  });
}

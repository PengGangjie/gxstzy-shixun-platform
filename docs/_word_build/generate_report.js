function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 120, after: 60, line: 560, lineRule: "exact" },
    indent: { firstLine: 640 },
    children: [new TextRun({ text, bold: false, size: 32, color: "000000",
      font: { eastAsia: "SimHei", ascii: "Times New Roman" } })],
  });
}

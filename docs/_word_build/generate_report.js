function makeTable(headers, rows, widths) {
  const cellPara = (text, isHeader) => new Paragraph({
    alignment: AlignmentType.LEFT,
    spacing: { line: 300, lineRule: "atLeast" },
    children: [new TextRun({ text: String(text == null || text === "" ? "\u2014" : text), bold: false, size: 21,
      color: "000000", font: { eastAsia: isHeader ? "SimHei" : "FangSong", ascii: "Times New Roman" } })],
  });
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    layout: TableLayoutType.FIXED,
    borders: {
      top: { style: BorderStyle.SINGLE, size: 6, color: "000000" },
      bottom: { style: BorderStyle.SINGLE, size: 6, color: "000000" },
      left: NB, right: NB,
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: "808080" },
      insideVertical: NB,
    },
    rows: [
      new TableRow({
        tableHeader: true, cantSplit: true,
        children: headers.map((text, i) => new TableCell({
          children: [cellPara(text, true)],
          shading: { type: ShadingType.CLEAR, fill: "F2F2F2" },
          margins: { top: 60, bottom: 60, left: 100, right: 100 },
          width: { size: widths[i], type: WidthType.PERCENTAGE },
        })),
      }),
      ...rows.map(row => new TableRow({
        cantSplit: true,
        children: row.map((text, i) => new TableCell({
          children: [cellPara(text, false)],
          margins: { top: 50, bottom: 50, left: 100, right: 100 },
          width: { size: widths[i], type: WidthType.PERCENTAGE },
        })),
      })),
    ],
  });
}
